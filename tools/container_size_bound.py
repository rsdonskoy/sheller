#!/usr/bin/env python3
"""Derive the crafted-container size bound from build inputs.

The bound is never hand-written: it is computed from the synthetic module
directory actually generated for the build, the test sample's SizeOfImage,
and the engine constants that reserve the environment/stack/heap/KUSER
regions. The output header is consumed by the container-size assertions.

Formula:
  (sum of module SizeOfImage + kEnvBlockSize + sample SizeOfImage
   + stack + heap + KUSER page) * 1.25

The x64 module sum is pinned by the EXPECTED_MODULE_BYTES_X64 constant below;
a mismatch fails the generation so a manifest drift cannot silently widen the
threshold (the frozen eight-module directory sums to 2,162,688).
"""

import argparse
import pathlib
import re
import struct
import sys

SCALE_NUM = 5
SCALE_DEN = 4

EXPECTED_MODULE_BYTES_X64 = 2162688


def read_le32(data, offset):
    return struct.unpack_from("<I", data, offset)[0]


def size_of_image(path):
    data = path.read_bytes()
    if len(data) < 0x40 or data[0:2] != b"MZ":
        raise ValueError(f"{path}: not an MZ image")
    pe = read_le32(data, 0x3C)
    if pe + 24 > len(data) or data[pe:pe + 4] != b"PE\0\0":
        raise ValueError(f"{path}: PE signature missing")
    optional = pe + 24
    magic = struct.unpack_from("<H", data, optional)[0]
    if magic not in (0x10B, 0x20B):
        raise ValueError(f"{path}: unsupported optional header magic {magic:#x}")
    size = read_le32(data, optional + 56)
    if size == 0:
        raise ValueError(f"{path}: SizeOfImage is zero")
    return size


def parse_cpp_constant(path, name):
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(
        r"\b" + re.escape(name) + r"\s*=\s*(0x[0-9A-Fa-f]+|[0-9]+)(?:ULL|UL|U|L)?\b")
    match = pattern.search(text)
    if match is None:
        raise ValueError(f"{path}: constant {name} not found")
    return int(match.group(1), 0)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--synth-dir", required=True,
                        help="directory with the generated .x64.dll modules")
    parser.add_argument("--sample", required=True, help="x64 sample PE file")
    parser.add_argument("--loader-env", required=True, help="src/loader/env.h")
    parser.add_argument("--rebuild-state", required=True, help="src/engine/rebuild_state.h")
    parser.add_argument("--header", required=True, help="generated header path")
    args = parser.parse_args()

    synth_dir = pathlib.Path(args.synth_dir)
    modules = sorted(synth_dir.glob("*.x64.dll"))
    if not modules:
        raise ValueError(f"{synth_dir}: no .x64.dll modules found")
    module_bytes = sum(size_of_image(path) for path in modules)

    env = pathlib.Path(args.loader_env)
    env_block = parse_cpp_constant(env, "kEnvBlockSize")
    rebuild_state = pathlib.Path(args.rebuild_state)
    stack_bytes = parse_cpp_constant(rebuild_state, "kLoaderStackSize")
    heap_bytes = parse_cpp_constant(rebuild_state, "kLoaderHeapSize")
    page_bytes = parse_cpp_constant(rebuild_state, "kMapAlignment")

    sample = size_of_image(pathlib.Path(args.sample))
    base = module_bytes + env_block + sample + stack_bytes + heap_bytes + page_bytes
    bound = (base * SCALE_NUM + SCALE_DEN - 1) // SCALE_DEN

    if module_bytes != EXPECTED_MODULE_BYTES_X64:
        raise ValueError(
            f"x64 module SizeOfImage sum is {module_bytes}, expected "
            f"{EXPECTED_MODULE_BYTES_X64}")

    header = pathlib.Path(args.header)
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text(
        "// Generated by tools/container_size_bound.py - do not edit.\n"
        "// Inputs: synth_modules SizeOfImage sum, sample SizeOfImage, engine reserves.\n"
        "\n"
        "#ifndef SHELLER_CONTAINER_SIZE_BOUND_H\n"
        "#define SHELLER_CONTAINER_SIZE_BOUND_H\n"
        "\n"
        "#include <cstdint>\n"
        "\n"
        "namespace sheller::test {\n"
        "\n"
        f"inline constexpr std::uint64_t kContainerModuleBytes = {module_bytes};\n"
        f"inline constexpr std::uint64_t kContainerEnvBytes = {env_block};\n"
        f"inline constexpr std::uint64_t kContainerSampleBytes = {sample};\n"
        f"inline constexpr std::uint64_t kContainerReserveBytes = "
        f"{stack_bytes + heap_bytes + page_bytes};\n"
        f"inline constexpr std::uint64_t kContainerSizeBound = {bound};\n"
        "\n"
        "} // namespace sheller::test\n"
        "\n"
        "#endif // SHELLER_CONTAINER_SIZE_BOUND_H\n",
        encoding="ascii")

    print(f"modules={module_bytes} env={env_block} sample={sample} "
          f"reserve={stack_bytes + heap_bytes + page_bytes} bound={bound}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
