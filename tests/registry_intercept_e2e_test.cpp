TEST(RegistryInterceptE2E, OpenQueryCloseChain)
{
    const auto wrapped = build_pe();
    ASSERT_TRUE(wrapped.has_value());
    const auto pe_path = fs::temp_directory_path() / "sheller_registry_e2e.exe";
    {
        std::ofstream out(pe_path, std::ios::binary | std::ios::trunc);
        out.write(reinterpret_cast<const char*>(wrapped->data()),
                  static_cast<std::streamsize>(wrapped->size()));
    }

    sheller::engine::SyscallRunOptions options;
    options.timeout_ms = 60000;
    const auto stats = sheller::engine::run_pe_file(pe_path, options);
    ASSERT_TRUE(stats.has_value()) << static_cast<int>(stats.error().error);
    EXPECT_TRUE(stats->terminated);
    // the full chain held: open ok, first query 2 (ERROR_FILE_NOT_FOUND),
    // close ok, stale-handle query 6 - the sample's own success exit
    EXPECT_EQ(stats->exit_code, 0x5678U);
}

TEST(RegistryInterceptE2E, HandleAndEventsDeterministicAcrossRuns)
{
    sheller::behavior::EventLedger first;
    sheller::behavior::EventLedger second;
    for (auto* ledger : {&first, &second}) {
        const auto wrapped = build_pe();
        ASSERT_TRUE(wrapped.has_value());
        const auto pe_path = fs::temp_directory_path() / "sheller_registry_det.exe";
        {
            std::ofstream out(pe_path, std::ios::binary | std::ios::trunc);
            out.write(reinterpret_cast<const char*>(wrapped->data()),
                      static_cast<std::streamsize>(wrapped->size()));
        }
        sheller::engine::SyscallRunOptions options;
        options.timeout_ms = 60000;
        options.event_sink = [ledger](const sheller::EventTypeId type,
                                      const sheller::EventPreamble& preamble,
                                      const std::span<const std::uint8_t> fields) {
            ledger->record(type, preamble, fields);
        };
        const auto stats = sheller::engine::run_pe_file(pe_path, options);
        ASSERT_TRUE(stats.has_value());
        ASSERT_TRUE(stats->terminated);
        EXPECT_EQ(stats->exit_code, 0x5678U);
    }
    // the three registry apicalls ride the ledger identically across runs
    ASSERT_EQ(first.size(), second.size());
    EXPECT_EQ(first.count_of(sheller::EventTypeId::kApiCall),
              second.count_of(sheller::EventTypeId::kApiCall));
    EXPECT_GE(first.count_of(sheller::EventTypeId::kApiCall), 4U); // open+query+close+stale
}

