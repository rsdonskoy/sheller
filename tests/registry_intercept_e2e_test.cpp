std::expected<std::vector<std::uint8_t>, sheller::capture::WrapError> build_pe()
{
    const auto blob = build_registry_blob();
    auto wrapped = sheller::capture::wrap_blob(sheller::capture::WrapArch::kX64, blob);
    if (!wrapped.has_value()) {
        return wrapped;
    }
    auto& pe = *wrapped;
    const std::uint32_t dir_va = 0x10D0; // descriptor block (blob 0xD0)
    const std::uint32_t dir_sz = 0x28;
    std::memcpy(&pe[0x58 + 112 + 8], &dir_va, 4);
    std::memcpy(&pe[0x58 + 112 + 12], &dir_sz, 4);
    return wrapped;
}

