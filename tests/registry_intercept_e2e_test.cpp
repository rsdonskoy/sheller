// Registry interception e2e: a bare blob with an
// advapi32 import table rides the loader route - RegOpenKeyExA opens a key
// (deterministic handle), RegQueryValueExA answers ERROR_FILE_NOT_FOUND
// (the honest value-absent branch), RegCloseKey drops the entry, and a
// stale-handle query answers ERROR_INVALID_HANDLE. Windows-host route
// (advapi32 is a resident real module there).

